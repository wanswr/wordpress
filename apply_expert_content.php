$pages = get_posts(array('post_type' => 'page', 'posts_per_page' => -1, 'post_status' => 'publish'));

$updated_count = 0;

foreach ($pages as $page) {
    $id = $page->ID;
    $slug = $page->post_name;
    $content = $page->post_content;

    // Check if page is already filled (expert text > 500 chars)
    $clean_text = strip_tags($content);
    $clean_text = preg_replace('/Также работаем в этих городах|Наши основные услуги|Ремонт и обслуживание|Освещение и трековые системы/iu', '', $clean_text);
    if (mb_strlen(trim($clean_text)) > 500 && !isset($content_plan[$slug])) {
        echo "Skipping already filled page: $slug\n";
        continue;
    }

    $expert_text = "";

    // 1. From Content Plan
    if (isset($content_plan[$slug])) {
        $expert_text = "\n<div class='expert-content'>\n" . nl2br($content_plan[$slug]) . "\n</div>\n";
    }
    // 2. GEO Template
    elseif (preg_match('/в\s+([А-Яа-яё\-]+)/iu', $page->post_title, $matches) && mb_stripos($page->post_title, 'Натяжные потолки') !== false) {
        $city = $matches[1];
        $expert_text = "\n<div class='expert-content'>\n<p>Компания Potolokbel предлагает профессиональный монтаж натяжных потолков в " . $city . " и прилегающих районах. Мы работаем на рынке более 10 лет, используя только сертифицированные полотна (MSD, Pongs, Teqtum) и современное оборудование.</p>\n<p>Наши специалисты выполняют установку любой сложности: от классических матовых решений до инновационных световых линий и теневых профилей EuroKRAAB. Мы гарантируем чистоту при монтаже, отсутствие запаха и долговечность конструкции. Выезд замерщика в " . $city . " — бесплатно в день обращения.</p>\n</div>\n";
    }
    // 3. Generic template for services if still empty
    elseif (mb_strlen(trim($clean_text)) < 300 && !in_array($slug, ['uslugi', 'katalog', 'home', 'kontakty', 'privacy-policy'])) {
        $expert_text = "\n<div class='expert-content'>\n<p>Ищете качественные " . mb_strtolower($page->post_title) . " в Москве? Мы предлагаем профессиональные решения по доступным ценам. Наша команда обеспечивает полный цикл работ: от бесплатного замера до чистового монтажа.</p>\n<p>Мы используем проверенные материалы от ведущих производителей и современное оборудование, что позволяет нам давать гарантию на работы до 15 лет. Оформите заявку сегодня и получите расчет стоимости вашего потолка в течение 15 минут!</p>\n</div>\n";
    }

    if ($expert_text) {
        // Insert after H1
        if (preg_match('/(<h1>.*?<\/h1>)/iu', $content, $m)) {
            $new_content = str_replace($m[1], $m[1] . $expert_text, $content);
        } else {
            $new_content = $expert_text . $content;
        }

        $wpdb->update($wpdb->posts, ['post_content' => $new_content], ['ID' => $id]);
        $updated_count++;
        echo "Updated page content: $slug\n";
    }
}

echo "TOTAL PAGES UPDATED WITH EXPERT CONTENT: $updated_count\n";
